class SeedQueryService:
    def __init__(self, mapping: dict[str, list[str]] | None = None) -> None:
        self.mapping = mapping or {}

    def generate_for_seed(self, seed: SeedProduct) -> Result:
        if seed.ozon_query_terms_ru and generated_query_terms_are_safe(seed.title_or_keyword, seed.ozon_query_terms_ru):
            query = SeedSearchQuery(
                seed_id=seed.seed_id,
                source_text_zh=seed.title_or_keyword,
                ozon_query_terms_ru=seed.ozon_query_terms_ru,
                auxiliary_query_terms_en=seed.auxiliary_query_terms_en,
                query_generation_method=seed.query_generation_method or "existing_seed_terms",
                query_generation_confidence=seed.query_generation_confidence or "high",
            )
            return Result.success("query.generated", "Seed already has safe Ozon query terms.", query.to_dict())

        mapped_terms = self.mapping.get(seed.title_or_keyword) or self.mapping.get(seed.product_clue)
        method = "manual_mapping"
        confidence = "high"
        if not mapped_terms:
            mapped_terms = self._auto_generate_terms(seed)
            method = "local_keyword_generator"
            confidence = "medium"
        if not mapped_terms:
            return Result.failure(
                "query.needs_generation",
                "Chinese seed needs Russian-first Ozon query generation before browsing.",
                data={"seed_id": seed.seed_id, "title_or_keyword": seed.title_or_keyword},
            )
        query = SeedSearchQuery(
            seed_id=seed.seed_id,
            source_text_zh=seed.title_or_keyword,
            ozon_query_terms_ru=mapped_terms,
            query_generation_method=method,
            query_generation_confidence=confidence,
        )
        errors = validate_seed_search_query(query)
        if errors:
            return Result.failure("query.invalid", "Generated Ozon query is not safe.", errors=errors)
        return Result.success("query.generated", "Generated safe Ozon query terms.", query.to_dict())

    def apply_query_to_seed(self, seed: SeedProduct, query: SeedSearchQuery) -> SeedProduct:
        seed.ozon_query_terms_ru = list(query.ozon_query_terms_ru)
        seed.auxiliary_query_terms_en = list(query.auxiliary_query_terms_en)
        seed.query_generation_status = QueryGenerationStatus.GENERATED
        seed.query_generation_method = query.query_generation_method
        seed.query_generation_confidence = query.query_generation_confidence
        return seed

    def _auto_generate_terms(self, seed: SeedProduct) -> list[str]:
        exact_terms = BUNDLED_SEED_QUERY_OVERRIDES.get(seed.title_or_keyword)
        if exact_terms is None:
            exact_terms = BUNDLED_SEED_QUERY_OVERRIDES.get(seed.product_clue)
        if exact_terms:
            return list(exact_terms)
        source = f"{seed.title_or_keyword} {seed.product_clue}".strip()
        for keyword, terms in AUTO_QUERY_OVERRIDES:
            if keyword in source:
                return terms
        noun = self._match_keyword(source, NOUN_QUERY_KEYWORDS)
        if not noun:
            return []
        modifiers = [value for keyword, value in QUERY_MODIFIERS if keyword in source and value not in noun]
        primary = " ".join([*modifiers[:2], noun]).strip()
        terms = [primary or noun]
        if noun not in terms:
            terms.append(noun)
        return terms

    def _match_keyword(self, source: str, mapping: tuple[tuple[str, str], ...]) -> str | None:
        matches = [(keyword, value) for keyword, value in mapping if keyword in source]
        if not matches:
            return None
        return max(matches, key=lambda item: len(item[0]))[1]
